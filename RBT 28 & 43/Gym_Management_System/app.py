from datetime import date, timedelta
from flask import Flask, render_template, request, redirect, url_for, flash
import mysql.connector

app = Flask(__name__)
app.secret_key = "gym-secret"


DB = dict(host="localhost", user="root", password="1234", port = 3306,database="gym_db")
PLAN_DAYS = {"Monthly": 30, "Quarterly": 90, "Half-Yearly": 180, "Yearly": 365}


def query(sql, args=(), one=False, commit=False):
    conn = mysql.connector.connect(**DB)
    cur = conn.cursor(dictionary=True)
    cur.execute(sql, args)
    if commit:
        conn.commit()
        result = cur.lastrowid
    else:
        rows = cur.fetchall()
        result = (rows[0] if rows else None) if one else rows
    cur.close()
    conn.close()
    return result

# HTTP requests
@app.route("/")
def dashboard():
    stats = {
        "members": query("SELECT COUNT(*) c FROM member", one=True)["c"],
        "active": query("SELECT COUNT(DISTINCT member_id) c FROM membership "
                        "WHERE CURDATE() BETWEEN start_date AND end_date", one=True)["c"],
        "revenue": query("SELECT COALESCE(SUM(amount),0) c FROM payment", one=True)["c"],
        "trainers": query("SELECT COUNT(*) c FROM trainer", one=True)["c"],
    }
    expiring = query("SELECT m.name, ms.plan_type, ms.end_date FROM member m "
                     "JOIN membership ms ON m.member_id=ms.member_id "
                     "WHERE ms.end_date BETWEEN CURDATE() AND DATE_ADD(CURDATE(), INTERVAL 7 DAY)")
    return render_template("index.html", s=stats, expiring=expiring)


@app.route("/members")
def members():
    rows = query("SELECT d.*, (SELECT GROUP_CONCAT(phone_no SEPARATOR ', ') FROM member_phone p "
                 "WHERE p.member_id=d.member_id) phones FROM member_details d ORDER BY d.member_id")
    return render_template("members.html", members=rows)


@app.route("/members/add", methods=["GET", "POST"])
def add_member():
    if request.method == "POST":
        f = request.form
        mid = query("INSERT INTO member (name, street, city, state, dob, trainer_id) "
                    "VALUES (%s,%s,%s,%s,%s,%s)",
                    (f["name"], f["street"], f["city"], f["state"], f["dob"],
                     f["trainer_id"] or None), commit=True)
        for ph in filter(None, (p.strip() for p in f["phones"].split(","))):
            query("INSERT IGNORE INTO member_phone VALUES (%s,%s)", (mid, ph), commit=True)
        flash("Member added!")
        return redirect(url_for("member_detail", mid=mid))
    return render_template("member_form.html", trainers=query("SELECT * FROM trainer"))


@app.route("/members/<int:mid>")
def member_detail(mid):
    m = query("SELECT * FROM member_details WHERE member_id=%s", (mid,), one=True)
    return render_template(
        "member_detail.html", m=m, plans=PLAN_DAYS, today=date.today(),
        phones=query("SELECT phone_no FROM member_phone WHERE member_id=%s", (mid,)),
        memberships=query("SELECT * FROM membership WHERE member_id=%s ORDER BY membership_no", (mid,)),
        payments=query("SELECT * FROM payment WHERE member_id=%s ORDER BY payment_date DESC", (mid,)))

    
@app.route("/members/<int:mid>/membership", methods=["POST"])
def add_membership(mid):
    plan = request.form["plan_type"]
    start = date.fromisoformat(request.form["start_date"])
    # membership_no is generated by the MySQL trigger
    query("INSERT INTO membership (member_id, plan_type, start_date, end_date) VALUES (%s,%s,%s,%s)",
          (mid, plan, start, start + timedelta(days=PLAN_DAYS[plan])), commit=True)
    flash("Membership added!")
    return redirect(url_for("member_detail", mid=mid))


@app.route("/members/<int:mid>/payment", methods=["POST"])
def add_payment(mid):
    f = request.form
    query("INSERT INTO payment (member_id, amount, payment_date, payment_mode) VALUES (%s,%s,%s,%s)",
          (mid, f["amount"], f["payment_date"], f["payment_mode"]), commit=True)
    flash("Payment recorded!")
    return redirect(url_for("member_detail", mid=mid))


@app.route("/members/<int:mid>/delete", methods=["POST"])
def delete_member(mid):
    query("DELETE FROM member WHERE member_id=%s", (mid,), commit=True)
    flash("Member deleted.")
    return redirect(url_for("members"))


@app.route("/trainers", methods=["GET", "POST"])
def trainers():
    if request.method == "POST":
        f = request.form
        query("INSERT INTO trainer (trainer_name, specialization, phone_no) VALUES (%s,%s,%s)",
              (f["trainer_name"], f["specialization"], f["phone_no"]), commit=True)
        flash("Trainer added!")
        return redirect(url_for("trainers"))
    rows = query("SELECT t.*, COUNT(m.member_id) total FROM trainer t "
                 "LEFT JOIN member m ON t.trainer_id=m.trainer_id GROUP BY t.trainer_id")
    return render_template("trainers.html", trainers=rows)


if __name__ == "__main__":
    app.run(debug=True)
