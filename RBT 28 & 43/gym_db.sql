-- =====================================================
--  USEFUL QUERIES (these will become your app features)
-- =====================================================

-- A. All members with age and trainer
SELECT * FROM member_details;

-- B. All phone numbers of every member
SELECT m.name, GROUP_CONCAT(p.phone_no) AS phones
FROM member m
LEFT JOIN member_phone p ON m.member_id = p.member_id
GROUP BY m.member_id, m.name;

-- C. Membership history of a member (e.g. member 1)
SELECT m.name, ms.membership_no, ms.plan_type, ms.start_date, ms.end_date
FROM membership ms
JOIN member m ON ms.member_id = m.member_id
WHERE m.member_id = 1
ORDER BY ms.membership_no;

-- D. Members whose membership is active today
SELECT DISTINCT m.member_id, m.name, ms.plan_type, ms.end_date
FROM member m
JOIN membership ms ON m.member_id = ms.member_id
WHERE CURDATE() BETWEEN ms.start_date AND ms.end_date;

-- E. Memberships expiring in the next 7 days
SELECT m.name, ms.plan_type, ms.end_date
FROM member m
JOIN membership ms ON m.member_id = ms.member_id
WHERE ms.end_date BETWEEN CURDATE() AND DATE_ADD(CURDATE(), INTERVAL 7 DAY);

-- F. Total amount paid by each member
SELECT m.member_id, m.name, COALESCE(SUM(p.amount), 0) AS total_paid
FROM member m
LEFT JOIN payment p ON m.member_id = p.member_id
GROUP BY m.member_id, m.name
ORDER BY total_paid DESC;

-- G. Payment history with member name
SELECT p.payment_id, m.name, p.amount, p.payment_date, p.payment_mode
FROM payment p
JOIN member m ON p.member_id = m.member_id
ORDER BY p.payment_date DESC;

-- H. Number of members under each trainer
SELECT t.trainer_id, t.trainer_name, t.specialization, COUNT(m.member_id) AS total_members
FROM trainer t
LEFT JOIN member m ON t.trainer_id = m.trainer_id
GROUP BY t.trainer_id, t.trainer_name, t.specialization;

-- I. Monthly revenue
SELECT DATE_FORMAT(payment_date, '%Y-%m') AS month, SUM(amount) AS revenue
FROM payment
GROUP BY month
ORDER BY month;

-- J. Revenue by payment mode
SELECT payment_mode, COUNT(*) AS no_of_payments, SUM(amount) AS total
FROM payment
GROUP BY payment_mode;

-- K. Members who never made a payment
SELECT m.member_id, m.name
FROM member m
LEFT JOIN payment p ON m.member_id = p.member_id
WHERE p.payment_id IS NULL;

