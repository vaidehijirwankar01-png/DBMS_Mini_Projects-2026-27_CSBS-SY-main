DROP DATABASE IF EXISTS gym_db;
CREATE DATABASE gym_db;
USE gym_db;

-- -----------------------------------------------------
-- 1. TRAINER
-- -----------------------------------------------------
CREATE TABLE trainer (
    trainer_id      INT AUTO_INCREMENT PRIMARY KEY,
    trainer_name    VARCHAR(100) NOT NULL,
    specialization  VARCHAR(100),
    phone_no        VARCHAR(15)
);

-- -----------------------------------------------------
-- 2. MEMBER
--    Address is composite  -> street, city, state
--    Age is derived        -> calculated in a VIEW (see below)
--    "Trained By" (M:1)    -> trainer_id foreign key
-- -----------------------------------------------------
CREATE TABLE member (
    member_id   INT AUTO_INCREMENT PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    street      VARCHAR(100),
    city        VARCHAR(50),
    state       VARCHAR(50),
    dob         DATE NOT NULL,
    trainer_id  INT NULL,
    CONSTRAINT fk_member_trainer
        FOREIGN KEY (trainer_id) REFERENCES trainer(trainer_id)
        ON DELETE SET NULL ON UPDATE CASCADE
);

-- -----------------------------------------------------
-- 3. MEMBER_PHONE  (Phone_No is multivalued -> separate table)
-- -----------------------------------------------------
CREATE TABLE member_phone (
    member_id  INT,
    phone_no   VARCHAR(15),
    PRIMARY KEY (member_id, phone_no),
    CONSTRAINT fk_phone_member
        FOREIGN KEY (member_id) REFERENCES member(member_id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- -----------------------------------------------------
-- 4. MEMBERSHIP  (WEAK ENTITY)
--    Primary key = owner's key (member_id) + partial key (membership_no)
--    "Enrolls" (1:M) -> one member, many memberships
-- -----------------------------------------------------
CREATE TABLE membership (
    member_id      INT,
    membership_no  INT NOT NULL DEFAULT 0,
    plan_type      ENUM('Monthly','Quarterly','Half-Yearly','Yearly') NOT NULL,
    start_date     DATE NOT NULL,
    end_date       DATE NOT NULL,
    PRIMARY KEY (member_id, membership_no),
    CONSTRAINT fk_membership_member
        FOREIGN KEY (member_id) REFERENCES member(member_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_dates CHECK (end_date > start_date)
);

-- Auto-number membership_no separately for every member (1, 2, 3 ...)
DELIMITER $$
CREATE TRIGGER trg_membership_no
BEFORE INSERT ON membership
FOR EACH ROW
BEGIN
    IF NEW.membership_no = 0 THEN
        SET NEW.membership_no =
            (SELECT COALESCE(MAX(membership_no), 0) + 1
             FROM membership
             WHERE member_id = NEW.member_id);
    END IF;
END$$
DELIMITER ;

-- -----------------------------------------------------
-- 5. PAYMENT
--    "Makes" (1:M) -> one member, many payments
-- -----------------------------------------------------
CREATE TABLE payment (
    payment_id    INT AUTO_INCREMENT PRIMARY KEY,
    member_id     INT NOT NULL,
    amount        DECIMAL(10,2) NOT NULL CHECK (amount > 0),
    payment_date  DATE NOT NULL,
    payment_mode  ENUM('Cash','UPI','Card','Net Banking') NOT NULL,
    CONSTRAINT fk_payment_member
        FOREIGN KEY (member_id) REFERENCES member(member_id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- -----------------------------------------------------
-- 6. VIEW for the derived attribute AGE
-- -----------------------------------------------------
CREATE VIEW member_details AS
SELECT  m.member_id,
        m.name,
        CONCAT_WS(', ', m.street, m.city, m.state) AS address,
        m.dob,
        TIMESTAMPDIFF(YEAR, m.dob, CURDATE()) AS age,
        t.trainer_name
FROM member m
LEFT JOIN trainer t ON m.trainer_id = t.trainer_id;

