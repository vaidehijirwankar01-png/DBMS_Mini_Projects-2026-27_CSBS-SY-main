-- SQLite schema (demo / test mode). Same tables as MySQL.
CREATE TABLE IF NOT EXISTS Librarian (
  Librarian_ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Username TEXT NOT NULL UNIQUE,
  Full_Name TEXT NOT NULL,
  Password_Hash TEXT NOT NULL,
  Role TEXT NOT NULL DEFAULT 'librarian' CHECK (Role IN ('admin','librarian')),
  Created_On TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS Member (
  Member_ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Name TEXT NOT NULL, Department TEXT, Phone TEXT UNIQUE,
  Joined_On TEXT DEFAULT CURRENT_DATE
);
CREATE TABLE IF NOT EXISTS Book (
  Book_ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Title TEXT NOT NULL, Author TEXT NOT NULL, Category TEXT,
  Quantity INTEGER NOT NULL DEFAULT 0 CHECK (Quantity >= 0)
);
CREATE TABLE IF NOT EXISTS Issue (
  Issue_ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Member_ID INTEGER NOT NULL REFERENCES Member(Member_ID),
  Book_ID INTEGER NOT NULL REFERENCES Book(Book_ID),
  Issue_Date TEXT NOT NULL, Due_Date TEXT NOT NULL, Return_Date TEXT,
  Renewed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS Fine (
  Fine_ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Issue_ID INTEGER NOT NULL UNIQUE REFERENCES Issue(Issue_ID),
  Amount INTEGER NOT NULL CHECK (Amount >= 0),
  Paid INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS Audit_Log (
  Log_ID INTEGER PRIMARY KEY AUTOINCREMENT,
  Username TEXT NOT NULL, Action TEXT NOT NULL, Detail TEXT,
  Logged_At TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_book_title ON Book(Title);
CREATE INDEX IF NOT EXISTS idx_issue_open ON Issue(Return_Date);
CREATE INDEX IF NOT EXISTS idx_issue_member ON Issue(Member_ID);
